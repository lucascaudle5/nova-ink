// Copies the BUILT notebook app (../engine-app/dist/notebook.html, from `npm run build` in ../engine-app) into
// src/engine/widget.generated.ts so the engine Worker can serve it as ui://nova-ink-engine/notebook.
// src/engine/widget.generated.ts is git-ignored.
//
//   node scripts/copy-engine-widget.mjs               copy the real app (fails if it was not built)
//   node scripts/copy-engine-widget.mjs --if-missing  tests/typecheck: write a tiny placeholder if the file does not exist yet
import { createHash } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const out = path.join(root, 'src', 'engine', 'widget.generated.ts')
const source = path.join(root, '..', 'engine-app', 'dist', 'notebook.html')
const ifMissing = process.argv.includes('--if-missing')

if (ifMissing && existsSync(out)) process.exit(0)

let html, kind
if (existsSync(source)) { html = readFileSync(source, 'utf8'); kind = 'built notebook app' }
else if (ifMissing) { html = '<!doctype html><title>NOVA Ink notebook placeholder</title><p>Build engine-app before deploying.</p>'; kind = 'placeholder' }
else { console.error(`Notebook app not built: ${source} is missing. Run "npm run build" in engine-app first.`); process.exit(1) }

const sha256 = createHash('sha256').update(html).digest('hex')
writeFileSync(out, `// GENERATED by scripts/copy-engine-widget.mjs (${kind}). Do not edit or commit.\nexport const ENGINE_WIDGET_INFO = ${JSON.stringify({ kind, bytes: Buffer.byteLength(html), sha256 })}\nexport const ENGINE_WIDGET_HTML: string = ${JSON.stringify(html)}\n`)
console.log(`engine widget.generated.ts: ${kind}, ${(Buffer.byteLength(html) / 1024).toFixed(0)} KiB, sha256 ${sha256.slice(0, 12)}…`)
