// Copies the BUILT notebook app (../engine-app/dist/notebook.html, from `npm run build` in ../engine-app) into
// src/engine/widget.generated.ts so the engine Worker can serve it as ui://nova-ink-engine/notebook.
// src/engine/widget.generated.ts is git-ignored.
//
//   node scripts/copy-engine-widget.mjs               copy the real app (fails if it was not built)
//   node scripts/copy-engine-widget.mjs --if-missing  tests/typecheck: write a tiny placeholder if the file does not exist yet
import { createHash } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const out = path.join(root, 'src', 'engine', 'widget.generated.ts')
const source = path.join(root, '..', 'engine-app', 'dist', 'notebook.html')
const ifMissing = process.argv.includes('--if-missing')

if (!(ifMissing && existsSync(out))) {
  let html, kind
  if (existsSync(source)) { html = readFileSync(source, 'utf8'); kind = 'built notebook app' }
  else if (ifMissing) { html = '<!doctype html><title>NOVA Ink notebook placeholder</title><p>Build engine-app before deploying.</p>'; kind = 'placeholder' }
  else { console.error(`Notebook app not built: ${source} is missing. Run "npm run build" in engine-app first.`); process.exit(1) }

  const sha256 = createHash('sha256').update(html).digest('hex')
  writeFileSync(out, `// GENERATED by scripts/copy-engine-widget.mjs (${kind}). Do not edit or commit.\nexport const ENGINE_WIDGET_INFO = ${JSON.stringify({ kind, bytes: Buffer.byteLength(html), sha256 })}\nexport const ENGINE_WIDGET_HTML: string = ${JSON.stringify(html)}\n`)
  console.log(`engine widget.generated.ts: ${kind}, ${(Buffer.byteLength(html) / 1024).toFixed(0)} KiB, sha256 ${sha256.slice(0, 12)}…`)
}

// pdf.js (Apache-2.0, public library code) for PDF import, served by the Worker at /assets/pdfjs/<name> and loaded
// by the notebook only when a PDF is imported. Legacy build: it also runs on older iPadOS web views.
const pdfOut = path.join(root, 'src', 'engine', 'pdfjs.generated.ts')
const pdfDir = path.join(root, '..', 'node_modules', 'pdfjs-dist', 'legacy', 'build')
const pdfFiles = ['pdf.min.mjs', 'pdf.worker.min.mjs']
if (!(ifMissing && existsSync(pdfOut))) {
  const found = pdfFiles.every(f => existsSync(path.join(pdfDir, f)))
  if (!found && !ifMissing) { console.error(`pdf.js not installed: ${pdfDir}. Run "npm install" in the repository root.`); process.exit(1) }
  const files = Object.fromEntries(found ? pdfFiles.map(f => [f, readFileSync(path.join(pdfDir, f), 'utf8')]) : [])
  const version = found ? JSON.parse(readFileSync(path.join(pdfDir, '..', '..', 'package.json'), 'utf8')).version : 'missing'
  writeFileSync(pdfOut, `// GENERATED by scripts/copy-engine-widget.mjs (pdf.js ${version}). Do not edit or commit.\nexport const PDFJS_VERSION = ${JSON.stringify(version)}\nexport const PDFJS_FILES: Record<string, string> = ${JSON.stringify(files)}\n`)
  console.log(`engine pdfjs.generated.ts: pdf.js ${version}, ${(Object.values(files).reduce((n, t) => n + Buffer.byteLength(t), 0) / 1024).toFixed(0)} KiB`)
}
