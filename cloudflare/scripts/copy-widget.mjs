// Copies the BUILT widget (../dist/mcp-app.html, produced by `npm run build` in the repo root) into
// src/widget.generated.ts so the Worker can serve it as the ui://nova-ink/canvas resource. Reads only; the Windows
// project is not modified. src/widget.generated.ts is git-ignored.
//
//   node scripts/copy-widget.mjs               copy the real widget (fails if it was not built)
//   node scripts/copy-widget.mjs --if-missing  tests/typecheck: write a tiny placeholder if the file does not exist yet
import { createHash } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const out = path.join(root, 'src', 'widget.generated.ts')
const source = path.join(root, '..', 'dist', 'mcp-app.html')
const ifMissing = process.argv.includes('--if-missing')

if (ifMissing && existsSync(out)) process.exit(0)

let html, kind
if (existsSync(source)) { html = readFileSync(source, 'utf8'); kind = 'built widget' }
else if (ifMissing) { html = '<!doctype html><title>NOVA Ink widget placeholder</title><p>Run npm run widget before deploying.</p>'; kind = 'placeholder' }
else { console.error(`Widget not built: ${source} is missing. Run "npm run build" in the repo root first.`); process.exit(1) }

const sha256 = createHash('sha256').update(html).digest('hex')
writeFileSync(out, `// GENERATED by scripts/copy-widget.mjs (${kind}). Do not edit or commit.\nexport const WIDGET_INFO = ${JSON.stringify({ kind, bytes: Buffer.byteLength(html), sha256 })}\nexport const WIDGET_HTML: string = ${JSON.stringify(html)}\n`)
console.log(`widget.generated.ts: ${kind}, ${(Buffer.byteLength(html) / 1048576).toFixed(2)} MiB, sha256 ${sha256.slice(0, 12)}…`)
