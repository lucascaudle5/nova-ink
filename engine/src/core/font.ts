/**
 * A single-line ("stroke") font, so text and equations NOVA writes are ordinary ink strokes: they select, move,
 * erase, save, export and undo like handwriting, and no new kind of page item is needed.
 *
 * Glyphs are polylines on a grid where y points UP: baseline 0, capital and digit height CAP, lowercase height XH,
 * descenders to -2.5. Each glyph has an ink width `w`; the typesetter adds spacing. Round shapes are sampled from
 * ellipse arcs, so they stay smooth when the ink outline is built.
 */
export type Pt = [number, number]
export type Poly = Pt[]
export interface Glyph { w: number; strokes: Poly[] }

export const CAP = 8
export const XH = 5.5
export const DESCENT = 2.5

/** Points of an ellipse arc, angles in degrees counter-clockwise from +x (y up); a0 > a1 runs clockwise. */
function arc(cx: number, cy: number, rx: number, ry: number, a0: number, a1: number): Poly {
  const steps = Math.max(4, Math.ceil(Math.abs(a1 - a0) / 15))
  const out: Poly = []
  for (let i = 0; i <= steps; i++) {
    const a = ((a0 + ((a1 - a0) * i) / steps) * Math.PI) / 180
    out.push([cx + rx * Math.cos(a), cy + ry * Math.sin(a)])
  }
  return out
}
const p = (...n: number[]): Poly => { const out: Poly = []; for (let i = 0; i + 1 < n.length; i += 2) out.push([n[i], n[i + 1]]); return out }
const join = (...parts: Poly[]): Poly => parts.flat()
