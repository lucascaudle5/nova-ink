/** Aliases so typed forms and symbols work: ASCII lookalikes and a few Unicode variants. */
const ALIASES: Record<string, string> = { '−': '-', '–': '-', '—': '-', '’': "'", '‘': "'", '“': '"', '”': '"', '∆': 'Δ', '∑': 'Σ', 'µ': 'μ', 'ϕ': 'φ', 'ε': 'ε' }

/** The glyph for a character; unknown characters become a small box so a gap is visible rather than silent. */
export function glyphFor(ch: string): Glyph {
  const key = ALIASES[ch] ?? ch
  return GLYPHS[key] ?? GLYPHS[key.toLowerCase()] ?? UNKNOWN
}
const UNKNOWN: Glyph = g(4, p(0, 0, 4, 0, 4, 8, 0, 8, 0, 0))
export const hasGlyph = (ch: string) => (ALIASES[ch] ?? ch) in GLYPHS
